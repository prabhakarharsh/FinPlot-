let isRenderingFallback = false;

export function renderIcons(root = document) {
  // If native lucide is loaded and it's not our own fallback shim, use it
  if (typeof window !== 'undefined' && window.lucide && typeof window.lucide.createIcons === 'function' && !window.lucide._isFallbackShim) {
    try {
      window.lucide.createIcons();
      return;
    } catch (e) {
      console.warn('[Icons] Native lucide.createIcons failed, using SVG fallback:', e);
    }
  }

  // Fallback: replace <i data-lucide="..."> with clean inline SVG
  const elements = root.querySelectorAll('i[data-lucide]');
  elements.forEach(el => {
    const name = el.getAttribute('data-lucide');
    const content = SVG_ICONS[name];
    if (content) {
      const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
      svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
      svg.setAttribute('viewBox', '0 0 24 24');
      svg.setAttribute('fill', 'none');
      svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', '2');
      svg.setAttribute('stroke-linecap', 'round');
      svg.setAttribute('stroke-linejoin', 'round');
      svg.setAttribute('class', 'lucide lucide-' + name);

      // Copy width/height/style if provided on <i>
      const style = el.getAttribute('style');
      if (style) svg.setAttribute('style', style);
      svg.style.width = el.style.width || '1em';
      svg.style.height = el.style.height || '1em';
      svg.style.display = 'inline-block';
      svg.style.verticalAlign = 'middle';

      svg.innerHTML = content;
      el.replaceWith(svg);
    }
  });
}

// Global window shim to guarantee any third-party or sub-module lucide.createIcons() call never throws
if (typeof window !== 'undefined') {
  window.renderIcons = renderIcons;
  if (!window.lucide || typeof window.lucide.createIcons !== 'function') {
    window.lucide = {
      _isFallbackShim: true,
      createIcons: () => renderIcons(document)
    };
  }
}
